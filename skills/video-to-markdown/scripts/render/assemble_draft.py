#!/usr/bin/env python3
"""Assemble a Markdown draft from a transcript, frame manifest, and metadata.

The draft groups the transcript into sections (video chapters when available,
otherwise fixed time windows), links every heading to the video moment, and
places keyframes inside the section they belong to. The agent then condenses
each raw transcript block into clear prose.

Usage:
    python assemble_draft.py --transcript transcript.json --video-id VIDEO_ID \
        --frames frames/manifest.json --metadata metadata.json --out draft.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.common import fail, format_timestamp, timestamp_url  # noqa: E402

DRAFT_NOTICE = "<!-- Draft generated by assemble_draft.py. Condense every blockquote into prose, then delete this comment. -->"


def chapter_sections(chapters: List[Dict[str, Any]], duration: float) -> List[Dict[str, Any]]:
    """Turn video chapters into sections with start, end, and title."""
    sections = []

    for index, chapter in enumerate(chapters):
        start = float(chapter.get("start") or 0)
        following = chapters[index + 1].get("start") if index + 1 < len(chapters) else None
        end = float(chapter.get("end") or following or duration)
        sections.append({"start": start, "end": end, "title": chapter.get("title") or "Section %d" % (index + 1)})

    return sections


def window_sections(duration: float, window: float) -> List[Dict[str, Any]]:
    """Split the video into fixed time windows."""
    sections = []
    start = 0.0
    index = 1

    while start < duration:
        sections.append({"start": start, "end": min(start + window, duration), "title": "Part %d" % index})
        start += window
        index += 1

    return sections


def build_sections(
    entries: List[Dict[str, Any]],
    frames: List[Dict[str, Any]],
    chapters: List[Dict[str, Any]],
    duration: float,
    window: float,
) -> List[Dict[str, Any]]:
    """Group transcript entries and frames into sections."""
    layout = chapter_sections(chapters, duration) if chapters else window_sections(duration, window)

    for section in layout:
        section["text"] = " ".join(
            entry["text"].replace("\n", " ")
            for entry in entries
            if section["start"] <= entry["start"] < section["end"]
        )
        section["frames"] = [
            frame for frame in frames if section["start"] <= float(frame["time"]) < section["end"]
        ]

    return layout


def render_markdown(
    sections: List[Dict[str, Any]],
    video_id: str,
    metadata: Dict[str, Any],
    frames_dir: str,
) -> str:
    """Render the draft Markdown document."""
    title = metadata.get("title") or "Video notes"
    lines = [
        "---",
        'title: "%s"' % str(title).replace('"', "'"),
        'source: "https://www.youtube.com/watch?v=%s"' % video_id,
    ]

    if metadata.get("channel"):
        lines.append('channel: "%s"' % str(metadata["channel"]).replace('"', "'"))

    if metadata.get("duration_seconds"):
        lines.append('duration: "%s"' % format_timestamp(float(metadata["duration_seconds"])))

    lines += ["---", "", DRAFT_NOTICE, "", "# %s" % title, ""]

    for section in sections:
        heading = "## [%s](%s) %s" % (
            format_timestamp(section["start"]),
            timestamp_url(video_id, section["start"]),
            section["title"],
        )
        lines += [heading, ""]

        for frame in section["frames"]:
            lines += ["![Frame at %s](%s/%s)" % (format_timestamp(float(frame["time"])), frames_dir, frame["file"]), ""]

        if section["text"]:
            lines += ["> " + section["text"], ""]

    return "\n".join(lines).rstrip() + "\n"


def load_json(path: Optional[str]) -> Dict[str, Any]:
    """Load a JSON file or return an empty object when no path is given."""
    if not path:
        return {}

    return json.loads(Path(path).read_text(encoding="utf-8"))


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Assemble a Markdown draft from video extraction output")
    parser.add_argument("--transcript", required=True, help="Transcript JSON from get_transcript.py or transcribe_audio.py")
    parser.add_argument("--video-id", required=True, help="YouTube video ID used for timestamp links")
    parser.add_argument("--frames", help="manifest.json from extract_frames.py")
    parser.add_argument("--metadata", help="metadata.json from download_video.py")
    parser.add_argument("--window", type=float, default=120.0, help="Section length in seconds when there are no chapters (default: 120)")
    parser.add_argument("--frames-dir", default="frames", help="Folder name used in image links (default: frames)")
    parser.add_argument("--out", "-o", help="Write the draft to a file instead of stdout")
    args = parser.parse_args(argv)

    if not Path(args.transcript).is_file():
        fail("File not found: %s" % args.transcript)

    transcript = load_json(args.transcript)
    manifest = load_json(args.frames)
    metadata = load_json(args.metadata)
    entries = transcript.get("timestamped", [])
    last = entries[-1] if entries else {"start": 0, "duration": 0}
    duration = float(metadata.get("duration_seconds") or manifest.get("duration") or (last["start"] + last["duration"]))
    sections = build_sections(entries, manifest.get("frames", []), metadata.get("chapters", []), duration, args.window)
    draft = render_markdown(sections, args.video_id, metadata, args.frames_dir)

    if args.out:
        Path(args.out).write_text(draft, encoding="utf-8")
        sys.stdout.write(json.dumps({"file": args.out, "sections": len(sections)}) + "\n")
    else:
        sys.stdout.write(draft)

    return 0


if __name__ == "__main__":
    sys.exit(main())
