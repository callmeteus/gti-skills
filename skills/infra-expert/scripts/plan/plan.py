"""Create, check, render, summarize, and track infrastructure change plans.

A plan is one Markdown file at <nearest git root>/.gti/infra-expert/plans/<date>-<slug>.md.
The YAML front matter between the --- fences is the source of truth. The body
below BODY_MARKER is generated from that front matter by `render` and is never
edited by hand. This script uses a small, documented YAML subset: mappings,
block lists, list items that are mappings, quoted strings, booleans, integers,
and inline lists or mappings. Every string is written with double quotes so
the parser reads back exactly what was written.

Standard library only, Python 3.8+. Use python3 on macOS and Linux and python
or py -3 on Windows.
"""

import argparse
import datetime
import json
import os
import re
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parents[2]
TEMPLATE = SKILL_DIR / "assets" / "templates" / "plan.md"
BODY_MARKER = "<!-- plan-body: generated by plan.py render, do not edit below this line -->"
PLAN_PARTS = (".gti", "infra-expert", "plans")

PLAN_STATUSES = ("draft", "proposed", "approved", "rejected", "applying", "applied", "rolled-back", "failed")
STEP_STATUSES = ("pending", "approved", "applied", "verified", "skipped", "failed", "rolled-back")
RISKS = ("low", "medium", "high")
DOWNTIME = ("none", "needs-decision")
METHODS = ("pipeline", "mcp", "cli", "manual")
ROLLOUTS = ("rolling", "blue-green", "reload", "no-restart", "needs-downtime")
DECISIONS = ("approve", "reject")
REQUIRED_FIELDS = ("id", "title", "goal", "created", "status", "risk", "downtime")
STEP_TEXT_FIELDS = ("title", "target", "method", "change", "rollout", "backup", "verify", "rollback")


def fail(message, code=1):
    """Print an error on stderr and exit with the given status."""
    print(message, file=sys.stderr)
    raise SystemExit(code)


def now():
    """Current UTC time as a compact timestamp for approvals and logs."""
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def slugify(name):
    """Lowercase a name, turn non-alphanumeric runs into one hyphen, and cap at 40 characters."""
    slug = re.sub(r"[^a-z0-9]+", "-", (name or "plan").lower()).strip("-")
    return slug[:40].rstrip("-") or "plan"


def nearest_git_root(start):
    """Nearest ancestor of start that holds a .git entry, directory or file, or None."""
    current = Path(start).resolve()
    for folder in (current, *current.parents):
        if (folder / ".git").exists():
            return folder
    return None


def plans_folder(start):
    """Plans folder at the nearest git root, or at start outside any repository."""
    root = nearest_git_root(start) or Path(start).resolve()
    return root.joinpath(*PLAN_PARTS)


# The YAML subset: parse.

def split_top(text):
    """Split a comma separated inline list or mapping without splitting inside quotes or brackets."""
    parts = []
    depth = 0
    quote = None
    current = []
    for char in text:
        if quote:
            current.append(char)
            if char == quote:
                quote = None
            continue
        if char in "\"'":
            quote = char
            current.append(char)
        elif char in "[{":
            depth += 1
            current.append(char)
        elif char in "]}":
            depth -= 1
            current.append(char)
        elif char == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
    if current:
        parts.append("".join(current))
    return parts


def scalar(text):
    """Parse one YAML scalar from the supported subset."""
    value = text.strip()
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        return [scalar(part) for part in split_top(inner)] if inner else []
    if value.startswith("{") and value.endswith("}"):
        inner = value[1:-1].strip()
        result = {}
        for part in split_top(inner):
            key, _, item = part.partition(":")
            if key.strip():
                result[key.strip()] = scalar(item)
        return result
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        if value[0] == '"':
            try:
                return json.loads(value)
            except ValueError:
                return value[1:-1]
        return value[1:-1].replace("''", "'")
    if value == "true":
        return True
    if value == "false":
        return False
    if value in ("null", "~"):
        return ""
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    return value


def significant_lines(text):
    """Return (indent, content) pairs, skipping blank lines and full-line comments."""
    rows = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        rows.append((len(line) - len(line.lstrip(" ")), line.strip()))
    return rows


def parse_map(rows, index, indent):
    """Parse a mapping block starting at rows[index] with the given indent."""
    result = {}
    while index < len(rows):
        row_indent, content = rows[index]
        if row_indent < indent or content.startswith("- "):
            break
        if row_indent > indent:
            index += 1
            continue
        key, separator, value = content.partition(":")
        if not separator:
            index += 1
            continue
        key = key.strip()
        value = value.strip()
        index += 1
        if value:
            result[key] = scalar(value)
        elif index < len(rows) and rows[index][0] > indent:
            child = rows[index][0]
            result[key], index = parse_block(rows, index, child)
        else:
            result[key] = ""
    return result, index


def parse_list(rows, index, indent):
    """Parse a block list, including list items that are mappings."""
    items = []
    while index < len(rows):
        row_indent, content = rows[index]
        if row_indent < indent or not (content.startswith("- ") or content == "-"):
            break
        if row_indent > indent:
            index += 1
            continue
        rest = content[1:].strip()
        index += 1
        if not rest:
            if index < len(rows) and rows[index][0] > indent:
                child = rows[index][0]
                item, index = parse_block(rows, index, child)
            else:
                item = ""
            items.append(item)
            continue
        key, separator, value = rest.partition(":")
        if separator and not rest.startswith(("[", "{", '"', "'")):
            item = {}
            if value.strip():
                item[key.strip()] = scalar(value)
            elif index < len(rows) and rows[index][0] > indent:
                child = rows[index][0]
                item[key.strip()], index = parse_block(rows, index, child)
            else:
                item[key.strip()] = ""
            while index < len(rows) and rows[index][0] > indent and not rows[index][1].startswith("- "):
                child = rows[index][0]
                more, index = parse_map(rows, index, child)
                item.update(more)
            items.append(item)
        else:
            items.append(scalar(rest))
    return items, index


def parse_block(rows, index, indent):
    """Parse either a mapping or a list block, whichever starts at rows[index]."""
    if index >= len(rows):
        return "", index
    if rows[index][1].startswith("- ") or rows[index][1] == "-":
        return parse_list(rows, index, indent)
    return parse_map(rows, index, indent)


def parse_front_matter(text):
    """Return (front matter dict, body text) from a plan file."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing front matter opening fence")
    end = None
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            end = index
            break
    if end is None:
        raise ValueError("front matter closing fence not found")
    rows = significant_lines("\n".join(lines[1:end]))
    data = parse_block(rows, 0, 0)[0] if rows else {}
    if not isinstance(data, dict):
        raise ValueError("front matter must be a mapping")
    return data, "\n".join(lines[end + 1:])


# The YAML subset: emit.

def emit_scalar(value):
    """Write one scalar. Strings are always double quoted so parsing is exact."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if value is None:
        return '""'
    return json.dumps(str(value), ensure_ascii=False)


def dump_yaml(value, indent=0):
    """Write a value using only the supported YAML subset."""
    pad = " " * indent
    lines = []
    if isinstance(value, dict):
        for key, item in value.items():
            name = str(key)
            if isinstance(item, dict) and item:
                lines.append(pad + name + ":")
                lines.append(dump_yaml(item, indent + 2))
            elif isinstance(item, list) and item:
                lines.append(pad + name + ":")
                lines.append(dump_yaml(item, indent + 2))
            elif isinstance(item, dict):
                lines.append(pad + name + ": {}")
            elif isinstance(item, list):
                lines.append(pad + name + ": []")
            else:
                lines.append(pad + name + ": " + emit_scalar(item))
    elif isinstance(value, list):
        for item in value:
            if isinstance(item, dict) and item:
                block = dump_yaml(item, indent + 2).splitlines()
                lines.append(pad + "- " + block[0].lstrip())
                lines.extend(block[1:])
            elif isinstance(item, list) and item:
                lines.append(pad + "-")
                lines.append(dump_yaml(item, indent + 2))
            else:
                lines.append(pad + "- " + emit_scalar(item))
    else:
        lines.append(pad + emit_scalar(value))
    return "\n".join(lines)


# Rendering.

def text_of(value):
    """Format a field for prose or a table cell."""
    if isinstance(value, dict):
        parts = [key + ": " + text_of(item) for key, item in value.items() if item not in ("", None, [], {})]
        return "; ".join(parts) if parts else "none"
    if isinstance(value, list):
        return ", ".join(text_of(item) for item in value) if value else "none"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if value in (None, ""):
        return "none"
    return str(value).replace("\n", " ").replace("|", "\\|")


def downtime_text(data):
    """Format the downtime field as its kind plus its reason."""
    value = data.get("downtime")
    if isinstance(value, dict):
        kind = str(value.get("kind") or "none")
        reason = str(value.get("reason") or "")
        return kind + (": " + reason if reason else "")
    return text_of(value)


def cell(value):
    """Make a value safe for one Markdown table cell."""
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ")


def with_dot(value):
    """End a short phrase with exactly one period for use in a paragraph."""
    text = cell(value).rstrip(".")
    return text + "." if text else "none."


def approvals_text(data):
    """Format the approval list for the field table."""
    entries = data.get("approvals") or []
    if not isinstance(entries, list):
        return "none yet"
    parts = []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        part = "{who} {decision} on {when}".format(
            who=entry.get("who") or "unknown",
            decision=entry.get("decision") or "decided",
            when=entry.get("when") or "unknown")
        if entry.get("step"):
            part += " for step " + str(entry["step"])
        if entry.get("reason"):
            part += " (" + cell(entry["reason"]) + ")"
        parts.append(part)
    return "; ".join(parts) if parts else "none yet"


def is_approved(data, step_id):
    """True when the step has its own approve decision."""
    for entry in data.get("approvals") or []:
        if isinstance(entry, dict) and entry.get("decision") == "approve" and entry.get("step") == step_id:
            return True
    return False


def decisions(data):
    """Short strings for everything that still needs a person or a choice."""
    needed = []
    for step in data.get("steps") or []:
        if not isinstance(step, dict):
            continue
        sid = step.get("id") or "unknown"
        if step.get("rollout") == "needs-downtime":
            needed.append("step " + sid + " needs a downtime decision")
        if step.get("requires_approval") and not is_approved(data, sid):
            needed.append("step " + sid + " needs approval")
    for question in data.get("open_questions") or []:
        needed.append(str(question))
    return needed


def render_body(data):
    """Build the body below the marker from the front matter."""
    steps = data.get("steps") or []
    lines = [
        "Plan `{id}`: {title}. Goal: {goal} It has {count} step(s), risk is {risk}, "
        "and the status is {status}.".format(
            id=cell(data.get("id")), title=cell(data.get("title")),
            goal=cell(data.get("goal")), count=len(steps),
            risk=cell(data.get("risk")), status=cell(data.get("status"))),
        "",
        "| Field | Value |",
        "|-------|-------|",
        "| Goal | " + cell(data.get("goal")) + " |",
        "| Scope | " + cell(text_of(data.get("scope"))) + " |",
        "| Risk | " + cell(data.get("risk")) + " |",
        "| Downtime | " + cell(downtime_text(data)) + " |",
        "| Status | " + cell(data.get("status")) + " |",
        "| Approvals | " + approvals_text(data) + " |",
        "| Source | " + cell(text_of(data.get("source"))) + " |",
        "",
        "## Steps",
        "",
    ]
    if not steps:
        lines.append("No steps yet.")
    for number, step in enumerate(steps, 1):
        if not isinstance(step, dict):
            lines.append(str(number) + ". Invalid step entry.")
            continue
        lines.append(
            "{n}. **{title}** (`{id}`). Target `{target}`; method `{method}` with {change} "
            "Rollout `{rollout}`. Backup: {backup} Verify: {verify} Rollback: {rollback} "
            "Depends on {depends}. Requires approval: {approval}. Status: `{status}`.".format(
                n=number, title=cell(step.get("title")), id=cell(step.get("id")),
                target=cell(step.get("target")), method=cell(step.get("method")),
                change=with_dot(step.get("change")), rollout=cell(step.get("rollout")),
                backup=with_dot(text_of(step.get("backup"))), verify=with_dot(text_of(step.get("verify"))),
                rollback=with_dot(text_of(step.get("rollback"))),
                depends=cell(text_of(step.get("depends_on"))),
                approval="yes" if step.get("requires_approval") else "no",
                status=cell(step.get("status"))))
        for entry in step.get("log") or []:
            if isinstance(entry, dict):
                lines.append("   - Log " + cell(entry.get("at")) + ": " + cell(entry.get("text")))
    lines.extend(["", "## Needs your decision", ""])
    needed = decisions(data)
    if needed:
        lines.extend("- " + cell(item) for item in needed)
    else:
        lines.append("Nothing needs a decision.")
    lines.extend([
        "",
        "## How to apply",
        "",
        "Approve the plan, then ask the agent to apply plan `" + cell(data.get("id")) + "`.",
    ])
    return "\n".join(lines).rstrip() + "\n"


def compose(data):
    """Build the whole plan file from its front matter."""
    head = "---\n" + dump_yaml(data) + "\n---\n\n# Change plan: " + text_of(data.get("title"))
    return head + "\n\n" + BODY_MARKER + "\n\n" + render_body(data)


def body_after_marker(text):
    """Return the generated part of the body, or None when the marker is missing."""
    index = text.find(BODY_MARKER)
    if index < 0:
        return None
    return text[index + len(BODY_MARKER):].strip("\n")


def load(path):
    """Read a plan file and return its front matter and raw text."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        fail("could not read " + str(path) + ": " + str(exc))
    try:
        data, _ = parse_front_matter(text)
    except ValueError as exc:
        fail("invalid plan " + str(path) + ": " + str(exc))
    return data, text


def write_plan(path, data):
    """Write a plan file from its front matter and print the path."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(compose(data), encoding="utf-8")
    print(target.resolve())
    return target


# Validation.

def validate(data, text=None):
    """Return one line per problem in a plan."""
    errors = []
    for key in REQUIRED_FIELDS:
        if key not in data or data[key] in ("", None, [], {}):
            errors.append("missing '" + key + "'")
    if data.get("status") not in PLAN_STATUSES:
        errors.append("unknown plan status '" + str(data.get("status")) + "'")
    if data.get("risk") not in RISKS:
        errors.append("unknown risk '" + str(data.get("risk")) + "'")
    downtime = data.get("downtime")
    if isinstance(downtime, dict):
        if downtime.get("kind") not in DOWNTIME:
            errors.append("unknown downtime '" + str(downtime.get("kind")) + "'")
        if not downtime.get("reason"):
            errors.append("downtime has no reason")
    elif downtime not in DOWNTIME:
        errors.append("unknown downtime '" + str(downtime) + "'")

    if "steps" not in data:
        errors.append("missing 'steps'")
    steps = data.get("steps")
    if "steps" in data and not isinstance(steps, list):
        errors.append("'steps' must be a list")
    if not isinstance(steps, list):
        steps = []
    ids = []
    for step in steps:
        if not isinstance(step, dict):
            errors.append("step entry must be a mapping")
            continue
        sid = step.get("id") or "unknown"
        ids.append(sid)
        for key in STEP_TEXT_FIELDS + ("id",):
            if key not in step or step[key] in ("", None, [], {}):
                errors.append("step '" + sid + "' is missing '" + key + "'")
        for key, allowed in (("method", METHODS), ("rollout", ROLLOUTS), ("status", STEP_STATUSES)):
            if step.get(key) not in allowed:
                errors.append("step '" + sid + "' has unknown " + key + " '" + str(step.get(key)) + "'")
        if not isinstance(step.get("requires_approval"), bool):
            errors.append("step '" + sid + "' needs a boolean requires_approval")
        if step.get("rollout") == "needs-downtime" and not step.get("requires_approval"):
            errors.append("step '" + sid + "' needs downtime and must require approval")
        for key in ("depends_on", "log"):
            if key in step and not isinstance(step[key], list):
                errors.append("step '" + sid + "' has a non-list '" + key + "'")
    for sid in sorted(set(ids)):
        if ids.count(sid) > 1:
            errors.append("duplicate step id '" + sid + "'")
    known = set(ids)
    for step in steps:
        if not isinstance(step, dict):
            continue
        sid = step.get("id") or "unknown"
        for dep in step.get("depends_on") or []:
            if dep not in known:
                errors.append("step '" + sid + "' depends on unknown step '" + str(dep) + "'")
            elif dep == sid:
                errors.append("step '" + sid + "' depends on itself")

    approvals = data.get("approvals") or []
    if not isinstance(approvals, list):
        errors.append("'approvals' must be a list")
    else:
        for entry in approvals:
            if not isinstance(entry, dict):
                errors.append("approval entry must be a mapping")
                continue
            if entry.get("decision") not in DECISIONS:
                errors.append("approval has unknown decision '" + str(entry.get("decision")) + "'")
            if entry.get("step") and entry["step"] not in known:
                errors.append("approval names unknown step '" + str(entry["step"]) + "'")

    if text is not None:
        actual = body_after_marker(text)
        if actual is None:
            errors.append("body marker is missing")
        elif actual != render_body(data).strip("\n"):
            errors.append("body is stale; run 'plan.py render'")
    return errors


# Commands.

def target_path(folder, name):
    """Choose a unique plan path inside a folder."""
    candidate = folder / (name + ".md")
    suffix = 2
    while candidate.exists():
        candidate = folder / (name + "-" + str(suffix) + ".md")
        suffix += 1
    return candidate


def empty_plan(name, title, goal):
    """A draft plan with safe defaults for the fields the user has not filled in."""
    return {
        "id": name,
        "title": title,
        "goal": goal,
        "requested_by": "",
        "created": datetime.date.today().isoformat(),
        "status": "draft",
        "scope": [],
        "risk": "medium",
        "downtime": {"kind": "none", "reason": "To be filled in."},
        "approvals": [],
        "source": "",
        "steps": [],
    }


def cmd_new(args):
    """Create a draft plan from the template in the plans folder."""
    folder = plans_folder(args.start)
    folder.mkdir(parents=True, exist_ok=True)
    slug = slugify(args.slug or args.title)
    name = datetime.date.today().isoformat().replace("-", "") + "-" + slug
    path = target_path(folder, name)
    data = empty_plan(path.stem, args.title, args.goal)
    try:
        template = TEMPLATE.read_text(encoding="utf-8")
    except OSError as exc:
        fail("could not read template: " + str(exc))
    text = template.replace("{{front_matter}}", dump_yaml(data))
    text = text.replace("{{title}}", text_of(data["title"]))
    text = text.replace("{{body}}", render_body(data))
    path.write_text(text, encoding="utf-8")
    print(path.resolve())
    return 0


def cmd_check(args):
    """Validate a plan and report every problem."""
    data, text = load(args.file)
    errors = validate(data, text)
    for error in errors:
        print(error, file=sys.stderr)
    return 1 if errors else 0


def cmd_render(args):
    """Rewrite the body below the marker from the front matter."""
    data, _ = load(args.file)
    write_plan(args.file, data)
    return 0


def summary_message(data):
    """Short, plain text summary of a plan."""
    lines = [
        "Plan " + str(data.get("id")) + ": " + str(data.get("title")),
        "Goal: " + text_of(data.get("goal")),
        "Risk: " + text_of(data.get("risk")) + ". Downtime: " + with_dot(downtime_text(data))
        + " Status: " + text_of(data.get("status")) + ".",
        "Steps:",
    ]
    steps = data.get("steps") or []
    if not steps:
        lines.append("No steps yet.")
    for step in steps:
        lines.append("- " + str(step.get("id")) + ": " + str(step.get("title"))
                     + " (" + str(step.get("rollout")) + ", " + str(step.get("status")) + ")")
    needed = "; ".join(decisions(data)).rstrip(".")
    lines.append("Needs a decision: " + (needed + "." if needed else "none."))
    return "\n".join(lines)


def action_values(data):
    """Action identifiers. Values carry the plan id and, for steps, the step id only."""
    pid = str(data.get("id"))
    values = [
        ("Approve plan", "approve-plan:" + pid),
        ("Reject plan", "reject-plan:" + pid),
    ]
    for step in data.get("steps") or []:
        if isinstance(step, dict) and step.get("requires_approval"):
            sid = str(step.get("id"))
            values.append(("Approve " + sid, "approve-step:" + pid + ":" + sid))
            values.append(("Reject " + sid, "reject-step:" + pid + ":" + sid))
    return values


def slack_actions(data):
    """Block Kit actions for a chat bot to post."""
    elements = []
    for label, value in action_values(data):
        element = {"type": "button", "text": {"type": "plain_text", "text": label}, "value": value}
        if label == "Approve plan":
            element["style"] = "primary"
            element["action_id"] = "approve_plan"
        elif label == "Reject plan":
            element["action_id"] = "reject_plan"
        elif label.startswith("Approve "):
            element["action_id"] = "approve_step"
        else:
            element["action_id"] = "reject_step"
        elements.append(element)
    return {
        "blocks": [
            {"type": "section", "text": {"type": "mrkdwn", "text": "*" + str(data.get("title")) + "*"}},
            {"type": "actions", "elements": elements},
        ]
    }


def telegram_actions(data):
    """Inline keyboard actions for a chat bot to post."""
    values = action_values(data)
    rows = [values[:2]]
    for index in range(2, len(values), 2):
        rows.append(values[index:index + 2])
    return {"inline_keyboard": [
        [{"text": label, "callback_data": value} for label, value in row] for row in rows
    ]}


def cmd_summary(args):
    """Print a short message and, for chat formats, the action JSON."""
    data, _ = load(args.file)
    message = summary_message(data)
    if args.format == "text":
        print(message)
        return 0
    actions = slack_actions(data) if args.format == "slack" else telegram_actions(data)
    print(json.dumps({"message": message, "actions": actions}, ensure_ascii=False, indent=2))
    return 0


def find_step(data, step_id):
    """Return a step by id or fail."""
    for step in data.get("steps") or []:
        if isinstance(step, dict) and step.get("id") == step_id:
            return step
    fail("step not found: " + str(step_id))


def append_log(step, text):
    """Append one timestamped entry to a step's log."""
    logs = step.get("log")
    if not isinstance(logs, list):
        logs = []
        step["log"] = logs
    logs.append({"at": now(), "text": str(text)})


def cmd_decide(args, decision):
    """Record an approve or reject decision and re-render the plan."""
    data, _ = load(args.file)
    reason = getattr(args, "reason", None)
    entry = {"decision": decision, "who": args.by, "when": now(), "step": args.step or ""}
    if reason:
        entry["reason"] = reason
    approvals = data.get("approvals")
    if not isinstance(approvals, list):
        approvals = []
        data["approvals"] = approvals
    approvals.append(entry)
    if args.step:
        step = find_step(data, args.step)
        if decision == "approve":
            if step.get("status") == "pending":
                step["status"] = "approved"
            word = "approved"
        else:
            step["status"] = "skipped"
            word = "rejected"
        append_log(step, word + " by " + args.by + (": " + reason if reason else ""))
    else:
        if decision == "approve" and data.get("status") in ("draft", "proposed", "rejected"):
            data["status"] = "approved"
        elif decision == "reject":
            data["status"] = "rejected"
    write_plan(args.file, data)
    return 0


def cmd_step(args):
    """Record an applying agent's progress on one step."""
    data, _ = load(args.file)
    step = find_step(data, args.id)
    if args.status == "applied":
        if step.get("requires_approval") and not is_approved(data, args.id):
            fail("step '" + args.id + "' requires approval before it can be applied")
        for dep in step.get("depends_on") or []:
            previous = find_step(data, dep)
            if previous.get("status") != "verified":
                fail("step '" + args.id + "' depends on '" + str(dep) + "' which is not verified")
    step["status"] = args.status
    if args.log:
        append_log(step, args.log)
    write_plan(args.file, data)
    return 0


def cmd_list(args):
    """List plans with their status, newest first."""
    folder = plans_folder(args.start)
    if not folder.is_dir():
        return 0
    rows = []
    for path in folder.glob("*.md"):
        try:
            data, _ = parse_front_matter(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        rows.append((path.name, str(data.get("status") or "unknown"), str(data.get("title") or "")))
    for name, status, title in sorted(rows, reverse=True):
        print(name[:-3] + "  " + status + "  " + title)
    return 0


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    new = commands.add_parser("new", help="Create a draft plan in the plans folder")
    new.add_argument("--title", required=True, help="Short title of the change")
    new.add_argument("--goal", required=True, help="What the change is meant to achieve")
    new.add_argument("--slug", default=None, help="Slug for the file name (default: derived from the title)")
    new.add_argument("--start", default=".", help="Folder to start from when finding the git root")
    new.set_defaults(func=cmd_new)

    check = commands.add_parser("check", help="Validate the schema and the generated body")
    check.add_argument("file", help="Plan Markdown file")
    check.set_defaults(func=cmd_check)

    render = commands.add_parser("render", help="Rewrite the body below the marker from the front matter")
    render.add_argument("file", help="Plan Markdown file")
    render.set_defaults(func=cmd_render)

    summary = commands.add_parser("summary", help="Print a short message and chat actions")
    summary.add_argument("file", help="Plan Markdown file")
    summary.add_argument("--format", choices=("text", "slack", "telegram"), default="text")
    summary.set_defaults(func=cmd_summary)

    approve = commands.add_parser("approve", help="Approve a plan or one step")
    approve.add_argument("file", help="Plan Markdown file")
    approve.add_argument("--step", default=None, help="Step id (default: the whole plan)")
    approve.add_argument("--by", required=True, help="Name of the person approving")
    approve.set_defaults(func=lambda args: cmd_decide(args, "approve"))

    reject = commands.add_parser("reject", help="Reject a plan or one step")
    reject.add_argument("file", help="Plan Markdown file")
    reject.add_argument("--step", default=None, help="Step id (default: the whole plan)")
    reject.add_argument("--by", required=True, help="Name of the person rejecting")
    reject.add_argument("--reason", default=None, help="Why the decision was made")
    reject.set_defaults(func=lambda args: cmd_decide(args, "reject"))

    step = commands.add_parser("step", help="Record the status of one step while applying")
    step.add_argument("file", help="Plan Markdown file")
    step.add_argument("id", help="Step id")
    step.add_argument("--status", required=True, choices=STEP_STATUSES, help="New step status")
    step.add_argument("--log", default=None, help="One timestamped log line to append")
    step.set_defaults(func=cmd_step)

    listing = commands.add_parser("list", help="List plans with status, newest first")
    listing.add_argument("--start", default=".", help="Folder to start from when finding the git root")
    listing.set_defaults(func=cmd_list)
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
