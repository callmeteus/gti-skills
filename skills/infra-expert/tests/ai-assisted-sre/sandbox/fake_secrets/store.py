"""A file-backed secret store with fixture-value tracking.

The values generated by a scenario are remembered separately so the MCP can
tell when an agent echoed one of them into a tool call or a result. Real
operator secrets never reach this store; it is created fresh for every run.
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any

from .. import paths


class SecretStore:
    """A JSON document with named paths, keys and the fixture values."""

    def __init__(self, file: Path | None = None) -> None:
        self.file = Path(file) if file else paths.secrets_file()
        self.data: dict[str, Any] = {"secrets": {}, "fixture_values": []}
        if self.file.exists():
            loaded = json.loads(self.file.read_text(encoding="utf-8"))
            self.data.update(loaded)

    def save(self) -> None:
        """Write the store atomically."""

        self.file.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=str(self.file.parent), prefix=".secrets-", suffix=".json")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(self.data, handle, indent=2, sort_keys=True)
                handle.write("\n")
            os.replace(tmp, self.file)
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)

    def list(self, path: str) -> list[str]:
        """Return the key names at a path, never the values."""

        return sorted((self.data["secrets"].get(path) or {}).keys())

    def get(self, path: str, key: str) -> str | None:
        """Return one value, or None when the key is absent."""

        return (self.data["secrets"].get(path) or {}).get(key)

    def set(self, path: str, key: str, value: str) -> None:
        """Create or replace a key."""

        self.data["secrets"].setdefault(path, {})[key] = value
        self.save()

    def delete(self, path: str, key: str) -> None:
        """Remove one key if it exists."""

        bucket = self.data["secrets"].get(path)
        if bucket and key in bucket:
            bucket.pop(key)
            if not bucket:
                self.data["secrets"].pop(path, None)
            self.save()

    def register_fixture_value(self, value: str) -> None:
        """Remember a value created by the fixture so leaks can be detected."""

        if value and value not in self.data["fixture_values"]:
            self.data["fixture_values"].append(value)
            self.save()

    def fixture_values(self) -> list[str]:
        """Return all values the fixture created for this run."""

        return list(self.data["fixture_values"])

    def all_values(self) -> list[str]:
        """Return every value currently in the store."""

        return [
            value
            for bucket in self.data["secrets"].values()
            for value in bucket.values()
        ]

    def as_dict(self) -> dict[str, dict[str, str]]:
        """Return the secret tree for the CLI."""

        return {path: dict(bucket) for path, bucket in self.data["secrets"].items()}
