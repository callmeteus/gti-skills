/** Text printed by `videoeditor help`. Every command also accepts `--json`. */
export function helpText(): string {
    return [
        "Video Editor - local-first, measured ffmpeg editing",
        "",
        "Usage: videoeditor <command> [flags] [--json]",
        "",
        "Detect and contract:",
        "  doctor                      Detect ffmpeg, filters, transcribers, and fonts",
        "  tools                       List every tool with inputs, outputs, and stability",
        "  status                      Tools, active request, and paths",
        "",
        "Edit and measure (each prints checks):",
        "  probe --source <path>       Refuse bad inputs, then report streams (or --all)",
        "  cut --source <f> --start <s> --end <s>   Cut and measure the result",
        "  trim-silence --source <f>   Detect and remove silent ranges",
        "  speed --source <f> --rate <n>            Change speed; warn outside 0.5x to 2x",
        "  reframe --source <f> --aspect 9:16       Crop, then report pixels removed",
        "  loudness --source <f>       Two-pass loudnorm with measured LUFS and A/V delta",
        "  export --source <f> --preset reels|shorts|tiktok|youtube",
        "  waveform --source <f> --at <t>          Waveform PNG around a cut point",
        "  frame --source <f> --at <t> [--compare-at <t>]",
        "  captions --source <f> [--srt <file>|--vtt <file>] [--style <name>]",
        "  review [--out <file>]       Static HTML review with checks and notes",
        "",
        "Motion graphics (experimental, needs Playwright and Chromium):",
        "  motion styles                   List starter Motion.md style guides",
        "  motion new --template <id>      Write an editable composition (--brand, --text, --preset)",
        "  motion render [--source <html>] Seek and encode MP4, or WebM with --alpha",
        "  motion analyze --source <ref>   Measure cuts, pacing, palette, and keyframes",
        "  motion add --as clip|overlay    Add a rendered motion clip at --at",
        "",
        "Timeline and state:",
        "  init --name <name>          Start a request (--new, --permanent)",
        "  plan                        Build the deterministic ffmpeg command",
        "  render [--out <path>]       Run the plan and write the export",
        "  scene add --source <path> --duration <sec>",
        "  music add --source <path>",
        "  history                     List requests in this session",
        "  studio [--port <n>]         Local review server, binds 127.0.0.1 by default",
        "  studio stop                 Stop a studio started in this process",
        "  demo [--out <dir>]          Write a sample timeline and plan without ffmpeg",
        "  resume                      Short status for the active request",
        "  help                        This text",
        "",
        "Common flags:",
        "  --json                      Print a JSON envelope on stdout",
        "  --session <id>              Override the detected chat session id",
        "  --request <id>              Open a specific request instead of the active one",
        "  --root <dir>                Workspace used to resolve relative source paths",
        "  --spec <path>               Use a timeline file instead of the active request's",
        "  --out <path>                Named destination for render, images, and review",
        "  --bind <address>            Studio bind; 0.0.0.0 or Tailscale only when explicit",
        "",
        "Every edit tool prints a `checks` array with measured results. The review page",
        "collects those checks, the inputs, and a clickable timeline of clips, captions,",
        "and audio. All generated state lives under ~/.gti/video-editor (GTI_HOME overrides it)."
    ].join("\n");
}
