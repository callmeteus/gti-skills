/**
 * Renders the short guide that tells one coding agent how to install and use one skill.
 *
 * The skill itself is identical for every agent; this guide holds only what differs.
 *
 * @param {{ id: string, displayName: string, harnessNotes: Record<string, string> }} skill Skill the guide is for
 * @param {import("./Registry.mjs").Harness} harness Agent the guide is for
 * @returns {string} Markdown text with LF line endings
 */
export function renderGuide(skill, harness) {
    const invoke = harness.slashCommand
        ? `You can also run it explicitly by typing \`/${skill.id}\`.`
        : `You can also name it in the request, for example: "Use the ${skill.id} skill to ...".`;
    const verify = harness.verify ?? `Ask the agent which skills it has loaded and check that \`${skill.id}\` is listed.`;
    const notes = [harness.notes];

    for (const key of ["*", harness.id]) {
        if (skill.harnessNotes[key]) {
            notes.push(skill.harnessNotes[key]);
        }
    }

    return [
        `# Using ${skill.displayName} in ${harness.name}`,
        "",
        "<!-- Generated by `node packages/cli build` from the harness registry. Do not edit by hand. -->",
        "",
        `The skill is the same in every agent. This guide covers only what is specific to ${harness.name}.`,
        "",
        "## Install",
        "",
        `Project scope (one repository): copy this skill folder to \`${harness.projectPath}/${skill.id}/\`.`,
        "",
        `User scope (every project): copy it to \`${harness.userPath}/${skill.id}/\`.`,
        "",
        "From the gti-skills repository, the CLI does the copy for you:",
        "",
        "```bash",
        `node packages/cli install --harness ${harness.id} --skill ${skill.id}`,
        `node packages/cli install --harness ${harness.id} --skill ${skill.id} --scope user`,
        "```",
        "",
        "Restart the agent session after installing so it rescans its skills.",
        "",
        "## Use",
        "",
        `Describe the task in plain language. ${harness.name} loads the skill when the request matches its \`description\`. ${invoke}`,
        "",
        "## Where the skill finds its files",
        "",
        `\`<skill-dir>\` in \`SKILL.md\` is the folder that contains \`SKILL.md\`: \`${harness.projectPath}/${skill.id}\` for a project install, or \`${harness.userPath}/${skill.id}\` for a user install. Scripts and references are always addressed relative to it.`,
        "",
        "## Verify",
        "",
        verify,
        "",
        "## Notes",
        "",
        ...notes.map((note) => `- ${note}`),
        `- Documentation: [${harness.name}](${harness.docs}) (path source: ${harness.source}).`,
        ""
    ].join("\n");
}

/**
 * Renders a generated document from the harness registry.
 *
 * @param {string} template Template name from skill.json
 * @param {import("./Registry.mjs").Harness[]} harnesses Harness registry
 * @returns {string} Markdown text with LF line endings
 */
export function renderGenerated(template, harnesses) {
    if (template === "install-locations") {
        return renderInstallLocations(harnesses);
    }

    throw new Error(`Unknown generated template: ${template}`);
}

/**
 * Renders the table of skill folders per coding agent.
 *
 * @param {import("./Registry.mjs").Harness[]} harnesses Harness registry
 * @returns {string} Markdown text
 */
function renderInstallLocations(harnesses) {
    const rows = harnesses.map((harness) => {
        return `| ${harness.name} | \`${harness.projectPath}/<skill-name>/\` | \`${harness.userPath}/<skill-name>/\` | ${harness.source} | [docs](${harness.docs}) |`;
    });

    return [
        "# Install locations",
        "",
        "<!-- Generated by `node packages/cli build` from the harness registry. Do not edit by hand. -->",
        "",
        "Every coding agent below loads the same skill folder (a folder with a `SKILL.md`). Copy the finished skill folder to the project path to scope it to one repository, or to the user path to make it available in every project, then restart the agent session.",
        "",
        "| Agent | Project path | User path | Path source | Docs |",
        "|-------|--------------|-----------|-------------|------|",
        ...rows,
        "",
        "`<skill-name>` is the folder name and must equal the `name` in the frontmatter.",
        "",
        "## Notes per agent",
        "",
        ...harnesses.map((harness) => `- **${harness.name}:** ${harness.notes}`),
        "",
        "## Copy commands",
        "",
        "macOS and Linux, Claude Code at project scope:",
        "",
        "```bash",
        "mkdir -p .claude/skills",
        "cp -r ./skills/<skill-name> .claude/skills/",
        "```",
        "",
        "Windows PowerShell, Claude Code at user scope:",
        "",
        "```powershell",
        "New-Item -ItemType Directory -Force \"$env:USERPROFILE\\.claude\\skills\" | Out-Null",
        "Copy-Item -Recurse .\\skills\\<skill-name> \"$env:USERPROFILE\\.claude\\skills\\\"",
        "```",
        "",
        "Paths marked `community` come from community reports and should be confirmed in the agent before relying on them.",
        ""
    ].join("\n");
}
